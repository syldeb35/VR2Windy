export function getLanguage() {
    if (typeof navigator === 'undefined') return 'en';
    const language = navigator.languages?.[0] || navigator.language || 'en';
    return language.toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

export function translate(key, values = {}, language = getLanguage()) {
    const message = messages[language]?.[key] ?? messages.en[key] ?? key;
    return message.replace(/\{(\w+)\}/g, (_match, name) => String(values[name] ?? `{${name}}`));
}
